import { app, BrowserWindow, session } from 'electron';
import * as path from 'path';
import * as fs from 'fs';

export interface UserAuthProfile {
  isLoggedIn: boolean;
  name?: string;
  email?: string;
  avatarUrl?: string;
  loginDate?: number;
}

export class AuthManager {
  private cookiesPath: string;
  private authMetaPath: string;
  private authWindow: BrowserWindow | null = null;

  constructor() {
    const userData = app.getPath('userData');
    this.cookiesPath = path.join(userData, 'yt_cookies.txt');
    this.authMetaPath = path.join(userData, 'yt_auth.json');
  }

  public getCookiesPath(): string {
    return this.cookiesPath;
  }

  public hasCookies(): boolean {
    return fs.existsSync(this.cookiesPath) && fs.statSync(this.cookiesPath).size > 50;
  }

  public getAuthStatus(): UserAuthProfile {
    try {
      if (this.hasCookies() && fs.existsSync(this.authMetaPath)) {
        const raw = fs.readFileSync(this.authMetaPath, 'utf-8');
        const data = JSON.parse(raw);
        return {
          isLoggedIn: true,
          name: data.name || 'Akun YouTube Music',
          email: data.email,
          avatarUrl: data.avatarUrl,
          loginDate: data.loginDate,
        };
      }
    } catch (e) {
      console.error('Error reading auth meta:', e);
    }
    return { isLoggedIn: false };
  }

  private convertCookiesToNetscape(cookies: Electron.Cookie[]): string {
    let output = '# Netscape HTTP Cookie File\n# This file was generated by AuraAudio\n\n';
    for (const c of cookies) {
      const rawDomain = c.domain || '.youtube.com';
      const domain = rawDomain.startsWith('.') ? rawDomain : `.${rawDomain}`;
      const flag = 'TRUE';
      const cookiePath = c.path || '/';
      const secure = c.secure ? 'TRUE' : 'FALSE';
      const expiration = c.expirationDate
        ? Math.round(c.expirationDate)
        : Math.round(Date.now() / 1000 + 365 * 24 * 3600);
      output += `${domain}\t${flag}\t${cookiePath}\t${secure}\t${expiration}\t${c.name}\t${c.value}\n`;
    }
    return output;
  }

  public async loginWithWindow(parentWindow?: BrowserWindow): Promise<UserAuthProfile> {
    if (this.authWindow && !this.authWindow.isDestroyed()) {
      this.authWindow.focus();
      return this.getAuthStatus();
    }

    const partition = 'persist:ytmusic_session';
    const authSession = session.fromPartition(partition);

    return new Promise((resolve, reject) => {
      this.authWindow = new BrowserWindow({
        width: 520,
        height: 720,
        parent: parentWindow || undefined,
        modal: !!parentWindow,
        title: 'Login Akun Google / YouTube Music',
        autoHideMenuBar: true,
        webPreferences: {
          session: authSession,
          nodeIntegration: false,
          contextIsolation: true,
        },
      });

      let checkInterval: NodeJS.Timeout | null = null;
      let isCompleted = false;

      const checkLoginStatus = async () => {
        if (isCompleted) return;
        try {
          const cookies = await authSession.cookies.get({ domain: '.youtube.com' });
          const hasSapisid = cookies.some((c) => c.name === 'SAPISID' || c.name === '__Secure-3PAPISID');
          const hasLoginInfo = cookies.some((c) => c.name === 'LOGIN_INFO');
          const hasSid = cookies.some((c) => c.name === 'SID');

          if ((hasSapisid || hasLoginInfo) && hasSid) {
            isCompleted = true;
            if (checkInterval) clearInterval(checkInterval);

            // Fetch all cookies from google and youtube
            const allCookies = await authSession.cookies.get({});
            const netscapeData = this.convertCookiesToNetscape(allCookies);
            fs.writeFileSync(this.cookiesPath, netscapeData, 'utf-8');

            const profile: UserAuthProfile = {
              isLoggedIn: true,
              name: 'Akun YouTube Music',
              loginDate: Date.now(),
            };

            fs.writeFileSync(this.authMetaPath, JSON.stringify(profile, null, 2), 'utf-8');

            if (this.authWindow && !this.authWindow.isDestroyed()) {
              this.authWindow.close();
            }
            this.authWindow = null;
            resolve(profile);
          }
        } catch (err) {
          console.error('Error during cookie check:', err);
        }
      };

      // Poll every 1.5 seconds for successful login state
      checkInterval = setInterval(checkLoginStatus, 1500);

      this.authWindow.on('closed', () => {
        if (checkInterval) clearInterval(checkInterval);
        this.authWindow = null;
        if (!isCompleted) {
          if (this.hasCookies()) {
            resolve(this.getAuthStatus());
          } else {
            resolve({ isLoggedIn: false });
          }
        }
      });

      // Navigate to Google ServiceLogin targeting YouTube Music
      this.authWindow.loadURL(
        'https://accounts.google.com/ServiceLogin?service=youtube&continue=https%3A%2F%2Fmusic.youtube.com%2F'
      );
    });
  }

  public async logout(): Promise<boolean> {
    try {
      if (fs.existsSync(this.cookiesPath)) {
        fs.unlinkSync(this.cookiesPath);
      }
      if (fs.existsSync(this.authMetaPath)) {
        fs.unlinkSync(this.authMetaPath);
      }

      const partition = 'persist:ytmusic_session';
      const authSession = session.fromPartition(partition);
      await authSession.clearStorageData();

      return true;
    } catch (e) {
      console.error('Logout error:', e);
      return false;
    }
  }
}
